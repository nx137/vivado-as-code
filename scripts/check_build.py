#!/usr/bin/env python3
"""check_build.py —— Vivado 构建日志门禁 + 时序检查 + 已知问题诊断。

为什么需要它：
    Vivado 里 **参数名写错通常只报 CRITICAL WARNING，不报 ERROR**，
    综合/实现甚至能跑完并产出 bit，但硬件行为是错的。
    因此"构建成功"不能只看退出码，必须扫日志。

用法：
    python check_build.py build.log
    python check_build.py build.log --manifest outputs/build_manifest.json
    python check_build.py build.log --explain            # 追加修复建议
    python check_build.py build.log --allow "^CRITICAL WARNING: \\[Labtools"

退出码：
    0 = 通过
    2 = 日志里有 ERROR 或 CRITICAL WARNING
    3 = 时序未收敛（manifest 里 WNS < 0）
    1 = 用法错误 / 文件不存在

说明：为跨平台稳定，命令行输出使用英文（Windows 控制台编码差异过大）；
      修复建议里的路径指向本仓库 references/pitfalls.md 的对应小节。
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ERROR_RE = re.compile(r"^\s*(ERROR|CRITICAL WARNING):", re.IGNORECASE)

# 已知问题模式库：id / 正则 / 一句话 / 修复动作 / 参考章节
KNOWN_ISSUES = [
    {
        "id": "BD-41-759",
        "regex": r"BD 41-759",
        "hint": "unconnected input pins were tied to 0",
        "action": "connect the per-port resets (S00_ARESETN/M00_ARESETN ...) or set "
                  "CONFIG.HAS_ARESETN {0} on the interconnect",
        "ref": "references/pitfalls.md B3",
    },
    {
        "id": "BD-41-758",
        "regex": r"BD 41-758",
        "hint": "clock pins are not connected to a valid clock source",
        "action": "connect M_AXI_GP0_ACLK / S_AXI_HPn_ACLK / interconnect ACLKs to FCLK_CLK0",
        "ref": "references/pitfalls.md B2",
    },
    {
        "id": "BD-41-701",
        "regex": r"BD 41-701",
        "hint": "connect_bd_net argument parsing failed",
        "action": "connect pin-to-pin (use an already-netted pin as anchor) instead of passing a net name",
        "ref": "references/pitfalls.md B5",
    },
    {
        "id": "BD-TCL-2041",
        "regex": r"BD::TCL 2041|BD 2041",
        "hint": "BD script generated by a different Vivado version",
        "action": "open the design in the target Vivado, run Report IP Status to upgrade, then write_bd_tcl again",
        "ref": "references/pitfalls.md A4",
    },
    {
        "id": "VIVADO-ENV",
        "regex": r"init\.tcl|utils\.tcl|ipgen",
        "hint": "Vivado environment / IP generation glitch (often transient)",
        "action": "close any GUI, rerun the build, then 'reset_target all' if it persists",
        "ref": "references/pitfalls.md A2",
    },
    {
        "id": "BD-41-2384",
        "regex": r"BD 41-2384",
        "hint": "AXI width mismatch (usually benign, but check the narrower side)",
        "action": "verify the IP data widths are intentional; mismatched widths silently drop upper bits",
        "ref": "references/pitfalls.md C",
    },
]

TIMING_HINT = {
    "id": "TIMING-WNS",
    "hint": "timing not met (WNS < 0)",
    "action": "check report_timing_summary; adjust output_delay / add multicycle / lower the clock",
    "ref": "references/pitfalls.md C7",
}


def _ascii_safe(text: str, limit: int = 200) -> str:
    return text[:limit].encode("ascii", "replace").decode("ascii")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Vivado build-log gate")
    p.add_argument("log", help="path to the Vivado build log")
    p.add_argument("--manifest", help="optional build_manifest.json")
    p.add_argument("--allow", action="append", default=[],
                   help="regex whitelist; matching lines are ignored (repeatable)")
    p.add_argument("--explain", action="store_true",
                   help="append actionable hints for known problems")
    p.add_argument("--json", action="store_true", help="print JSON only")
    return p.parse_args()


def collect_hints(failing_lines: list[str], timing_bad: bool) -> list[dict]:
    hints = []
    for issue in KNOWN_ISSUES:
        pattern = re.compile(issue["regex"], re.IGNORECASE)
        count = sum(1 for line in failing_lines if pattern.search(line))
        if count:
            hints.append({
                "id": issue["id"],
                "hint": issue["hint"],
                "action": issue["action"],
                "ref": issue["ref"],
                "count": count,
            })
    if timing_bad:
        hints.append({**TIMING_HINT, "count": 1})
    return hints


def main() -> int:
    # Windows 控制台可能是 GBK；日志里偶尔含无法解码的字符，避免打印时崩溃
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except (AttributeError, ValueError):
            pass

    args = parse_args()
    log_path = Path(args.log)
    if not log_path.is_file():
        print(f"log not found: {log_path}", file=sys.stderr)
        return 1

    allow = [re.compile(a) for a in args.allow]
    errors: list[tuple[int, str]] = []
    criticals: list[tuple[int, str]] = []
    ignored = 0

    with log_path.open("r", encoding="utf-8", errors="replace") as fh:
        for lineno, line in enumerate(fh, 1):
            if not ERROR_RE.match(line):
                continue
            if any(a.search(line) for a in allow):
                ignored += 1
                continue
            if line.lstrip().upper().startswith("ERROR"):
                errors.append((lineno, line.strip()))
            else:
                criticals.append((lineno, line.strip()))

    timing_ok = True
    wns = None
    manifest_ok = True
    if args.manifest and Path(args.manifest).is_file():
        try:
            data = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
            manifest_ok = str(data.get("status", "ok")) == "ok"
            raw = data.get("wns")
            if raw not in (None, "", "nan"):
                wns = float(raw)
                timing_ok = wns >= 0
        except (json.JSONDecodeError, ValueError):
            manifest_ok = False

    code = 0
    if errors or criticals or not manifest_ok:
        code = 2
    if wns is not None and wns < 0:
        code = 3

    failing_lines = [line for _, line in errors] + [line for _, line in criticals]
    hints = collect_hints(failing_lines, timing_bad=(wns is not None and wns < 0))

    report = {
        "log": str(log_path),
        "status": "pass" if code == 0 else "fail",
        "errors": len(errors),
        "critical_warnings": len(criticals),
        "ignored": ignored,
        "wns": wns,
        "exit_code": code,
        "suggestions": hints,
    }

    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return code

    print(f"log: {log_path}")
    print(f"  ERROR            : {len(errors)}")
    print(f"  CRITICAL WARNING : {len(criticals)}")
    if ignored:
        print(f"  ignored (allow)  : {ignored}")
    if wns is not None:
        print(f"  WNS              : {wns} ns -> {'PASS' if timing_ok else 'FAIL (timing not met)'}")

    def show(title: str, items: list[tuple[int, str]], limit: int = 15) -> None:
        if not items:
            return
        print(f"\n{title} (showing up to {limit}):")
        for lineno, line in items[:limit]:
            print(f"  L{lineno}: {_ascii_safe(line)}")
        if len(items) > limit:
            print(f"  ... {len(items) - limit} more, see the log")

    show("ERROR", errors)
    show("CRITICAL WARNING", criticals)

    if hints:
        print("\nHINTS:" if not args.explain else "\nHINTS (with action):")
        for h in hints:
            print(f"  [{h['id']}] {h['hint']} (x{h['count']})")
            if args.explain:
                print(f"      -> {h['action']}")
                print(f"      ref: {h['ref']}")

    if code == 0:
        print("\nRESULT: PASS")
    elif code == 3:
        print("\nRESULT: FAIL - timing not met (WNS < 0); fix constraints or reduce clock")
    else:
        print("\nRESULT: FAIL - ERROR / CRITICAL WARNING found. "
              "In Vivado, a mistyped IP parameter only produces a CRITICAL WARNING "
              "and silently falls back to the default; read properties back with get_property.")
    return code


if __name__ == "__main__":
    sys.exit(main())
